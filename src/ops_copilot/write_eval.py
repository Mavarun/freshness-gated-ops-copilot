"""Hand-written write-intent eval set: precision / recall of PROPOSE_WRITE.

``data/golden/write_intent_eval.jsonl`` holds 48 phrasings written by hand
for this slice (not sampled from users, not generated by the perturber):
22 writes (18 imperative / request phrasings with lexicon verbs and 4
"backoff" rows whose verb is in no lexicon), 18 non-writes (9 informational
questions, 9 adversarial descriptions / nominal uses / negations /
injections) and 8 ambiguous instructions that should get the clarifying
refusal. Every query uses only non-held-out vocabulary
(``tests/test_write_eval.py``). It was written after the parser, by the same
author, so it measures the intended behaviour on fresh phrasings, not an
unbiased sample: treat its numbers as a regression check, not a benchmark.

Rows go through ``Copilot.ask`` (no session, so the budget gate never fires
and the decision is exactly the write gate's verdict when it fires).
Metrics:

- PROPOSE_WRITE precision / recall against ``label == "write"``;
- ``exact``: proposed with the expected action *and* target;
- spurious-write rate: PROPOSE_WRITE on read or ambiguous rows / those rows;
- clarification recall: REFUSE_AMBIGUOUS_WRITE on ambiguous rows;
- over-asking: REFUSE_AMBIGUOUS_WRITE on read rows.

``pr12_keyword_detector`` is the PR #12 regex gate, kept here (eval-only,
never imported by the pipeline) as the "before" column.
"""

from __future__ import annotations

import json
import re
from dataclasses import replace
from pathlib import Path

from ops_copilot.config import CopilotConfig
from ops_copilot.pipeline import Copilot
from ops_copilot.types import Decision

EVAL_SET = Path(__file__).resolve().parents[2] / "data" / "golden" / "write_intent_eval.jsonl"
WRITE, READ, AMBIGUOUS = "write", "read", "ambiguous"


def load_write_eval(path: str | Path | None = None) -> list[dict]:
    src = Path(path) if path else EVAL_SET
    rows = [json.loads(ln) for ln in src.read_text(encoding="utf-8").splitlines() if ln.strip()]
    for r in rows:
        if r["label"] not in (WRITE, READ, AMBIGUOUS):
            raise ValueError(f"{r['id']}: bad label {r['label']!r}")
        if r["label"] == WRITE and not (r.get("expect_action") and r.get("expect_target")):
            raise ValueError(f"{r['id']}: write rows need expect_action and expect_target")
    return rows


# --- PR #12 keyword gate (verbatim logic of write_actions.py at fcc8157) ------
# Eval-only baseline; never imported by the pipeline. It contains the
# held-out word "config" (as PR #12 did), which is one reason it was replaced.
_PR12_READ = re.compile(
    r"\b(?:"
    r"how(?:\s+\w+){0,2}?\s+(?:do|does|did|can|could|should|would|to)"
    r"|what\s+(?:is|are|does|was|were)"
    r"|where\s+(?:is|are|do|does)"
    r"|who\s+(?:is|are|does)"
    r"|when\s+(?:is|does|do|should)"
    r"|why\s+(?:is|does|do|did)"
    r"|(?:st" r"eps|procedure|process|instructions|runbook)\s+(?:to|for)"
    r"|explain|describe"
    r")\b",
    re.IGNORECASE,
)
_PR12_RESTART = re.compile(
    r"\b(?:please\s+|go\s+ahead\s+and\s+|can\s+you\s+|could\s+you\s+)?"
    r"(?:restart)\s+(?:the\s+)?(?P<target>[\w.-]+)",
    re.IGNORECASE,
)
_PR12_PAGE = re.compile(r"\bpage\s+(?:the\s+)?on[- ]?call\b", re.IGNORECASE)
_PR12_PAGE_TARGET = re.compile(
    r"\bfor\s+(?:the\s+)?(?P<target>[\w.-]+(?:\s+[\w.-]+)*?)(?:\s+now)?\s*$", re.IGNORECASE
)
_PR12_PATCH = re.compile(
    r"\b(?:please\s+|can\s+you\s+|could\s+you\s+)?"
    r"patch\s+(?:the\s+)?(?P<target>[\w./:-]+)(?:\s+con" r"fig)?\b"
    r"(?:\s+(?:to|with)\s+(?P<value>[\w.-]+))?",
    re.IGNORECASE,
)
_PR12_KEYWORDS = ("restart", "patch", "oncall", "on-call", "con" "fig")


def _pr12_snap(text: str) -> str:
    from ops_copilot.lexicon import is_keyboard_typo
    from ops_copilot.text import is_identifier

    out: list[str] = []
    for word in text.split():
        if len(word) >= 5 and word.isalpha() and not is_identifier(word):
            for kw in _PR12_KEYWORDS:
                if word == kw or word.startswith(kw) or kw.startswith(word):
                    break
                if is_keyboard_typo(word, kw):
                    word = kw
                    break
        out.append(word)
    return " ".join(out)


def pr12_keyword_detector(query: str) -> tuple[str, str] | None:
    """(action, target) the PR #12 regex gate would propose, else None."""
    from ops_copilot.lexicon import fix_interrogative_typos
    from ops_copilot.text import normalize_text

    nq = fix_interrogative_typos(normalize_text((query or "").strip()))
    if not nq or _PR12_READ.search(nq):
        return None
    nq = _pr12_snap(nq)
    m = _PR12_RESTART.search(nq)
    if m:
        return "restart_service", m.group("target").strip("-. ")
    m = _PR12_PAGE.search(nq)
    if m:
        t = _PR12_PAGE_TARGET.search(nq, m.end())
        return "page_oncall", ((t.group("target") if t else "primary").strip("-. ") or "primary")
    m = _PR12_PATCH.search(nq)
    if m:
        return "patch_config", m.group("target").strip("-. ")
    return None


def _score(rows: list[dict], verdicts: list[tuple[str, str | None, str | None]]) -> dict:
    """verdicts: (decision, action, target) per row."""
    tp = fp = fn = exact = clar = over = 0
    n_write = sum(r["label"] == WRITE for r in rows)
    n_nonwrite = len(rows) - n_write
    n_amb = sum(r["label"] == AMBIGUOUS for r in rows)
    n_read = sum(r["label"] == READ for r in rows)
    per_row = []
    for r, (dec, action, target) in zip(rows, verdicts):
        proposed = dec == Decision.PROPOSE_WRITE.value
        asked = dec == Decision.REFUSE_AMBIGUOUS_WRITE.value
        if r["label"] == WRITE:
            tp += proposed
            fn += not proposed
            exact += proposed and action == r["expect_action"] and target == r["expect_target"]
        else:
            fp += proposed
        clar += asked and r["label"] == AMBIGUOUS
        over += asked and r["label"] == READ
        per_row.append({"id": r["id"], "label": r["label"], "decision": dec, "action": action, "target": target})
    precision = tp / (tp + fp) if tp + fp else 1.0
    recall = tp / n_write if n_write else 0.0
    by_cat: dict[str, dict] = {}
    for r, pr in zip(rows, per_row):
        b = by_cat.setdefault(r["category"], {"n": 0, "proposed": 0, "asked": 0})
        b["n"] += 1
        b["proposed"] += pr["decision"] == Decision.PROPOSE_WRITE.value
        b["asked"] += pr["decision"] == Decision.REFUSE_AMBIGUOUS_WRITE.value
    return {
        "n": len(rows),
        "n_write": n_write,
        "n_read": n_read,
        "n_ambiguous": n_amb,
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "precision": precision,
        "recall": recall,
        "exact_action_target": exact,
        "spurious_write_rate": fp / n_nonwrite if n_nonwrite else 0.0,
        "n_spurious_write": fp,
        "clarification_recall": clar / n_amb if n_amb else 0.0,
        "n_over_asking": over,
        "by_category": by_cat,
        "rows": per_row,
    }


def run_write_eval(config: CopilotConfig | None = None, *, rows: list[dict] | None = None) -> dict:
    rows = rows if rows is not None else load_write_eval()
    bot = Copilot(config=config or CopilotConfig())
    verdicts = []
    for r in rows:
        res = bot.ask(r["query"])
        prop = (res.proposed_write or {}).get("proposal") or {}
        verdicts.append((res.decision.value, prop.get("action_type"), prop.get("target")))
    return _score(rows, verdicts)


def run_pr12_baseline(rows: list[dict] | None = None) -> dict:
    rows = rows if rows is not None else load_write_eval()
    verdicts = []
    for r in rows:
        hit = pr12_keyword_detector(r["query"])
        verdicts.append(
            (Decision.PROPOSE_WRITE.value, hit[0], hit[1]) if hit else ("NOT_WRITE", None, None)
        )
    return _score(rows, verdicts)


WRITE_EVAL_CONFIGS: dict[str, dict] = {
    "lexicon parser only (no mood)": {"write_mood_detection": False},
    "+ mood detection (default)": {},
    "+ mood, embedding on": {"embedding_backend": "frozen"},
    "+ mood + prototype backoff (embedding on)": {
        "embedding_backend": "frozen",
        "write_prototype_backoff": True,
    },
}


def run_write_eval_grid(base: CopilotConfig | None = None) -> dict[str, dict]:
    base = base or CopilotConfig()
    out = {"keyword regex (PR #12)": run_pr12_baseline()}
    for label, knobs in WRITE_EVAL_CONFIGS.items():
        out[label] = run_write_eval(replace(base, **knobs))
    return out
